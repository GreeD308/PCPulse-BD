/**
 * Helper: find a product by id.
 */
export function getProductById(id) {
  return PRODUCT_CATALOG.find(p => p.id === id) ?? null
}

/**
 * Helper: resolve a shop object from BD_SHOPS by shopId.
 */
export function getShopById(shopId) {
  return BD_SHOPS.find(s => s.id === shopId) ?? { id: shopId, name: shopId, shortName: shopId, city: 'Dhaka' }
}

